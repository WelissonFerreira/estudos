            // 3. Se o item NÃO existe, adiciona ele ao carrinho com quantidade 1
            itensCarrinho.push({
                produtoId: seletorDoCarrinho, // Adicione o ID para fácil referência
                produto: produtoSelecionado,
                quantidade: 1
            });
